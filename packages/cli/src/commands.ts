import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export type Scope = 'ingest' | 'read';

/** `slk_<scope>_` + 32 random bytes, base64url: the format the collector accepts. */
export function newKey(scope: Scope): string {
  return `slk_${scope}_${randomBytes(32).toString('base64url')}`;
}

const secret = () => randomBytes(32).toString('base64');

/** The `.env` the collector reads. Every secret is generated here and never printed. */
function envFile(opts: { domain: string; appId: string; identifyUsers?: boolean | undefined }): string {
  return [
    '# Shardlens collector settings, generated by `shardlens init`. Never commit this file.',
    `SHARDLENS_DOMAIN=${opts.domain}`,
    `SHARDLENS_PUBLIC_URL=https://${opts.domain}`,
    `SHARDLENS_APP_ID=${opts.appId}`,
    `POSTGRES_PASSWORD=${randomBytes(24).toString('base64url')}`,
    `SHARDLENS_SESSION_SECRET=${secret()}`,
    `SHARDLENS_SETTINGS_KEY=${secret()}`,
    `SHARDLENS_INGEST_KEY=${newKey('ingest')}`,
    `SHARDLENS_READ_KEY=${newKey('read')}`,
    '',
    '# Optional: "Sign in with Discord" (OAuth2 → Redirects: https://<domain>/auth/discord/callback).',
    'DISCORD_CLIENT_ID=',
    'DISCORD_CLIENT_SECRET=',
    '# Optional: user-install tracking (Developer Portal → General Information → Public Key).',
    'DISCORD_PUBLIC_KEY=',
    opts.identifyUsers
      ? '# Lets you switch from hashed to identified users (audit mode) in Settings. Back this key up.'
      : '# To identify users instead of hashing them (audit mode), uncomment this and choose it in Settings.',
    `${opts.identifyUsers ? '' : '# '}SHARDLENS_AUDIT_KEY=${secret()}`,
    'LOG_LEVEL=info',
    '',
  ].join('\n');
}

function templatesDir(): string {
  const bundled = fileURLToPath(new URL('./templates/', import.meta.url));
  if (existsSync(join(bundled, 'docker-compose.yml'))) return bundled;
  return fileURLToPath(new URL('../../../deploy/', import.meta.url)); // running from source
}

export interface InitResult {
  dir: string;
  written: string[];
}

/** Writes docker-compose.yml, Caddyfile and .env into `dir`. Refuses to overwrite an existing .env unless `force`. */
export async function init(opts: {
  dir: string;
  domain: string;
  appId: string;
  force?: boolean;
  /** Also create the key that allows identified users (audit mode). */
  identifyUsers?: boolean;
}): Promise<InitResult> {
  if (!/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(opts.domain))
    throw new Error('--domain must be a hostname like stats.example.com');
  if (!/^\d{17,20}$/.test(opts.appId)) throw new Error('--app-id must be your Discord application ID');
  const dir = resolve(opts.dir);
  await mkdir(dir, { recursive: true });
  const env = join(dir, '.env');
  if (existsSync(env) && !opts.force) throw new Error(`${env} already exists (use --force to replace it)`);
  const templates = templatesDir();
  const written: string[] = [];
  for (const name of ['docker-compose.yml', 'Caddyfile']) {
    await writeFile(join(dir, name), await readFile(join(templates, name), 'utf8'));
    written.push(name);
  }
  await writeFile(env, envFile(opts), { mode: 0o600 });
  written.push('.env');
  return { dir, written };
}

export interface PrivacyOptions {
  audit?: boolean;
  /** Audit mode with `auditIncludeProfile: false`. */
  idsOnly?: boolean;
  optionValues?: string[];
  webhookEvents?: boolean;
  retentionDays?: number;
  auditRetentionDays?: number;
}

/** A plain-language paragraph for the bot's privacy policy, matching the configuration. Not legal advice. */
export function privacyParagraph(o: PrivacyOptions): string {
  const raw = o.retentionDays ?? 35;
  const parts = [
    'This bot uses Shardlens, a self-hosted analytics tool, to understand how it is used and to keep it reliable.',
    'When you use one of its commands, buttons or menus, it records which one, when, in which server (or in DMs), your Discord app language, whether you are using it as a server or user install, and whether it worked and how quickly.',
    o.optionValues?.length
      ? `For the options ${o.optionValues.map((v) => `"${v}"`).join(', ')} it also records the values you choose; other option values are not recorded.`
      : 'It records which command options you use, but not the values you enter.',
    o.audit
      ? `For support and abuse prevention it also records your Discord user ID${o.idsOnly ? '' : ', username and avatar'} with each command, encrypted, and keeps this for up to ${o.auditRetentionDays ?? 30} days. Access to this information is restricted to the bot's team and every access is logged.`
      : 'Your Discord user ID is replaced inside the bot with a pseudonymous code that changes every month; after the month ends the code can no longer be linked to you.',
    o.webhookEvents
      ? 'When you add or remove the bot, Discord tells us that it happened; your user ID is pseudonymised in the same way.'
      : '',
    'Shardlens never reads your messages, and the data stays on infrastructure run by the bot owner; it is not sold or shared with third parties.',
    `Detailed records are kept for ${raw} days; after that only anonymous totals remain.`,
    'You can stop this recording, or ask for your recorded data to be deleted, with the /privacy command or by contacting the bot owner.',
  ];
  return parts.filter(Boolean).join(' ');
}

export interface Check {
  name: string;
  ok: boolean;
  detail: string;
  warnOnly?: boolean;
}

function versionAtLeast(version: string, min: [number, number]): boolean {
  const [major = 0, minor = 0] = version.replace(/^v/, '').split('.').map(Number);
  return major > min[0] || (major === min[0] && minor >= min[1]);
}

/**
 * Finds a package the way Node does (the nearest `node_modules` upwards) and reads its version from disk, because
 * `require('<name>/package.json')` fails for packages that don't export that path.
 */
async function installedVersion(name: string, from: string): Promise<string | undefined> {
  for (let dir = from; ; dir = dirname(dir)) {
    try {
      const pkg = JSON.parse(await readFile(join(dir, 'node_modules', name, 'package.json'), 'utf8')) as {
        version?: unknown;
      };
      if (typeof pkg.version === 'string') return pkg.version;
    } catch {
      // not here: keep walking up
    }
    if (dirname(dir) === dir) return undefined;
  }
}

/** Setup checks. Network calls go only to the collector URL given (and nowhere else). */
export async function doctor(opts: {
  url?: string;
  key?: string;
  cwd?: string;
  fetchImpl?: typeof fetch;
}): Promise<Check[]> {
  const checks: Check[] = [];
  const f = opts.fetchImpl ?? fetch;
  checks.push({
    name: 'Node.js version',
    ok: versionAtLeast(process.version, [22, 12]),
    detail: `${process.version} (the SDK needs 22.12 or newer)`,
  });

  const cwd = resolve(opts.cwd ?? process.cwd());
  const djs = await installedVersion('discord.js', cwd);
  if (djs) {
    const supported = /^1[45]\./.test(djs);
    checks.push({
      name: 'discord.js',
      ok: supported,
      detail: `${djs}${supported ? '' : ' (Shardlens supports 14.x and 15.x)'}`,
    });
  } else if (await installedVersion('@shardlens/http', cwd)) {
    checks.push({ name: 'discord.js', ok: true, detail: 'not needed: this project uses @shardlens/http' });
  } else {
    checks.push({ name: 'discord.js', ok: false, detail: 'not installed in this project', warnOnly: true });
  }

  if (!opts.url) {
    checks.push({
      name: 'Collector',
      ok: false,
      detail: 'pass --url (or set SHARDLENS_URL) to check it',
      warnOnly: true,
    });
    return checks;
  }
  let url: URL;
  try {
    url = new URL(opts.url);
  } catch {
    checks.push({ name: 'Collector URL', ok: false, detail: 'not a valid URL' });
    return checks;
  }
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  checks.push({
    name: 'Collector URL',
    ok: url.protocol === 'https:' || (url.protocol === 'http:' && local),
    detail: url.protocol === 'https:' ? 'HTTPS' : local ? 'HTTP to localhost (development only)' : 'must be HTTPS',
  });
  try {
    const res = await f(new URL('/healthz', url), { signal: AbortSignal.timeout(5_000) });
    checks.push({ name: 'Collector reachable', ok: res.ok, detail: res.ok ? 'healthy' : `answered ${res.status}` });
  } catch (error) {
    checks.push({
      name: 'Collector reachable',
      ok: false,
      detail: error instanceof Error ? error.message : 'request failed',
    });
    return checks;
  }
  if (!opts.key) {
    checks.push({
      name: 'Ingest key',
      ok: false,
      detail: 'pass --key (or set SHARDLENS_INGEST_KEY) to check it',
      warnOnly: true,
    });
    return checks;
  }
  if (!/^slk_ingest_[\w-]{43}$/.test(opts.key)) {
    checks.push({ name: 'Ingest key', ok: false, detail: 'not an ingest key (expected slk_ingest_…)' });
    return checks;
  }
  try {
    const res = await f(new URL('/v1/config', url), {
      headers: { authorization: `Bearer ${opts.key}` },
      signal: AbortSignal.timeout(5_000),
    });
    if (!res.ok) {
      checks.push({ name: 'Ingest key', ok: false, detail: `rejected (${res.status})` });
    } else {
      const cfg = (await res.json()) as { appId: string; mode: string; saltPeriod: string; salts: unknown[] };
      checks.push({ name: 'Ingest key', ok: true, detail: `accepted for application ${cfg.appId}` });
      checks.push({ name: 'Data mode', ok: true, detail: `${cfg.mode}, salts rotate per ${cfg.saltPeriod}` });
      checks.push({
        name: 'Salt available',
        ok: cfg.salts.length > 0,
        detail: cfg.salts.length > 0 ? 'yes' : 'no salt served',
      });
    }
  } catch (error) {
    checks.push({ name: 'Ingest key', ok: false, detail: error instanceof Error ? error.message : 'request failed' });
  }
  return checks;
}
