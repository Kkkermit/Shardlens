import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { envValues, setEnvVariables } from './env-file.js';
import { newKey } from './keys.js';
import { list } from './list.js';

/** A mistake on the command line (exit code 2), as opposed to a failure while carrying it out. */
export class UsageError extends Error {}

const FILES = ['docker-compose.yml', 'Caddyfile', '.env', 'bot.env'];
const HOSTNAME = /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;

const secret = () => randomBytes(32).toString('base64');
const API_KEYS = new Set(['SHARDLENS_INGEST_KEY', 'SHARDLENS_READ_KEY']);

// What `init` generates. An existing .env keeps its own values: a new database password or settings key would lock
// the collector out of its database and encrypted settings.
const GENERATED: Record<string, () => string> = {
  // base64url, because it goes into the database URL.
  POSTGRES_PASSWORD: () => randomBytes(24).toString('base64url'),
  SHARDLENS_SESSION_SECRET: secret,
  SHARDLENS_SETTINGS_KEY: secret,
  SHARDLENS_INGEST_KEY: () => newKey('ingest'),
  SHARDLENS_READ_KEY: () => newKey('read'),
};

/** The `.env` the collector reads. */
function envFile(opts: {
  domain: string;
  appId: string;
  identifyUsers: boolean;
  values: Record<string, string>;
}): string {
  const generated = Object.keys(GENERATED).map((name) => `${name}=${opts.values[name]}`);
  return [
    '# Shardlens collector settings, generated by `shardlens init`. Never commit this file.',
    `SHARDLENS_DOMAIN=${opts.domain}`,
    `SHARDLENS_PUBLIC_URL=https://${opts.domain}`,
    `SHARDLENS_APP_ID=${opts.appId}`,
    ...generated,
    '',
    `# Optional: "Sign in with Discord". The client ID is your application ID (${opts.appId}); the secret is under`,
    `# OAuth2 in the Developer Portal, with the redirect https://${opts.domain}/auth/discord/callback.`,
    'DISCORD_CLIENT_ID=',
    'DISCORD_CLIENT_SECRET=',
    '# Optional: user-install tracking (Developer Portal → General Information → Public Key).',
    'DISCORD_PUBLIC_KEY=',
    opts.identifyUsers
      ? '# Lets you switch from hashed to identified users (audit mode) in Settings. Back this key up.'
      : '# To identify users instead of hashing them (audit mode), uncomment this and choose it in Settings.',
    `${opts.identifyUsers ? '' : '# '}SHARDLENS_AUDIT_KEY=${secret()}`,
    '# Optional: also copy every event into your own database (mongodb://, mysql://, mariadb://, postgres:// or',
    '# sqlite:/path). The dashboard keeps using the bundled PostgreSQL.',
    'SHARDLENS_SINK_URL=',
    'LOG_LEVEL=info',
    '',
  ].join('\n');
}

/** The two settings the bot needs, ready to copy to wherever it runs. */
function botEnvFile(url: string, ingestKey: string): string {
  return [
    '# Settings for your bot (not the collector), generated by `shardlens init`. Copy these two lines into the',
    "# bot's own .env or host settings, then delete this file. Never commit it.",
    `SHARDLENS_URL=${url}`,
    `SHARDLENS_INGEST_KEY=${ingestKey}`,
    '',
  ].join('\n');
}

/**
 * The variables to change in an existing collector `.env`: the ones `init` takes from its options, and generated ones
 * that are missing. API keys belong to the application they were first used with, so a new application ID gets new ones.
 */
function envUpdates(
  values: Record<string, string>,
  opts: { domain: string; appId: string; identifyUsers: boolean },
): Record<string, string> {
  const updates: Record<string, string> = {};
  const given = {
    SHARDLENS_DOMAIN: opts.domain,
    SHARDLENS_PUBLIC_URL: `https://${opts.domain}`,
    SHARDLENS_APP_ID: opts.appId,
  };
  for (const [name, value] of Object.entries(given)) if (values[name] !== value) updates[name] = value;
  const newApp = values.SHARDLENS_APP_ID !== undefined && values.SHARDLENS_APP_ID !== opts.appId;
  for (const [name, make] of Object.entries(GENERATED)) {
    if (!values[name] || (newApp && API_KEYS.has(name))) updates[name] = make();
  }
  if (opts.identifyUsers && !values.SHARDLENS_AUDIT_KEY) updates.SHARDLENS_AUDIT_KEY = secret();
  return updates;
}

function templatesDir(): string {
  const bundled = fileURLToPath(new URL('./templates/', import.meta.url));
  if (existsSync(join(bundled, 'docker-compose.yml'))) return bundled;
  return fileURLToPath(new URL('../../../deploy/', import.meta.url)); // running from source
}

interface InitResult {
  dir: string;
  /** The collector's address, which is also the bot's `SHARDLENS_URL`. */
  url: string;
  /** Files written from scratch. */
  written: string[];
  /** With `force` and an existing `.env`: the variables changed in it. Everything else in it was kept. */
  updated?: string[];
}

/**
 * Writes docker-compose.yml, Caddyfile, the collector's .env and bot.env (the bot's two settings) into `dir`. Refuses
 * when any of them is already there unless `force`, which replaces the others but updates an existing .env in place.
 */
export async function init(opts: {
  dir: string;
  domain: string;
  appId: string;
  force?: boolean;
  /** Also create the key that allows identified users (audit mode). */
  identifyUsers?: boolean;
}): Promise<InitResult> {
  const domain = opts.domain.toLowerCase();
  if (!HOSTNAME.test(domain)) {
    throw new UsageError(
      domain.includes('://')
        ? '--domain takes a hostname without https://, such as stats.example.com'
        : '--domain must be a hostname, such as stats.example.com',
    );
  }
  if (!/^\d{17,20}$/.test(opts.appId)) {
    throw new UsageError('--app-id must be your Discord application ID: 17 to 20 digits, from the Developer Portal');
  }
  const dir = resolve(opts.dir);
  const url = `https://${domain}`;
  const identifyUsers = opts.identifyUsers ?? false;
  try {
    await mkdir(dir, { recursive: true });
    const there = FILES.filter((name) => existsSync(join(dir, name)));
    if (there.length > 0 && !opts.force) {
      const kept = there.includes('.env') ? ' (.env keeps its secrets and settings)' : '';
      throw new Error(
        `${dir} already has ${list(there)}. Run again with --force to replace ${there.length > 1 ? 'them' : 'it'}${kept}.`,
      );
    }
    const env = join(dir, '.env');
    const text = there.includes('.env') ? await readFile(env, 'utf8') : undefined;
    const templates = templatesDir();
    const written: string[] = [];
    for (const name of ['docker-compose.yml', 'Caddyfile']) {
      await writeFile(join(dir, name), await readFile(join(templates, name), 'utf8'));
      written.push(name);
    }
    let values: Record<string, string>;
    let updated: string[] | undefined;
    if (text !== undefined) {
      const previous = envValues(text);
      const updates = envUpdates(previous, { domain, appId: opts.appId, identifyUsers });
      await writeSecret(env, setEnvVariables(text, updates));
      values = { ...previous, ...updates };
      updated = Object.keys(updates);
    } else {
      values = Object.fromEntries(Object.entries(GENERATED).map(([name, make]) => [name, make()]));
      await writeSecret(env, envFile({ domain, appId: opts.appId, identifyUsers, values }));
      written.push('.env');
    }
    await writeSecret(join(dir, 'bot.env'), botEnvFile(url, values.SHARDLENS_INGEST_KEY ?? ''));
    written.push('bot.env');
    return { dir, url, written, ...(updated ? { updated } : {}) };
  } catch (error) {
    throw explain(error);
  }
}

/** Writes a file only its owner can read. `mode` applies only to new files, so a replaced one is tightened too. */
async function writeSecret(path: string, content: string): Promise<void> {
  await writeFile(path, content, { mode: 0o600 });
  await chmod(path, 0o600);
}

const FS_REASONS: Record<string, string> = {
  EACCES: 'permission denied',
  EPERM: 'permission denied',
  EROFS: 'read-only file system',
  EEXIST: 'a file is in the way of the folder',
  ENOTDIR: 'a file is in the way of the folder',
  EISDIR: 'a folder is in the way of the file',
  ENOSPC: 'no space left on the disk',
};

/** A file-system error that names the path in plain words, instead of Node's `EACCES: permission denied, open …`. */
function explain(error: unknown): unknown {
  const { code, path } = error as NodeJS.ErrnoException;
  const reason = code === undefined ? undefined : FS_REASONS[code];
  return reason && path ? new Error(`${path}: ${reason} (${code})`) : error;
}
